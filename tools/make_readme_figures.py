"""Regenerate the README figures in docs/img/ from the files in data/.

    pip install pymupdf matplotlib
    python tools/make_readme_figures.py

pdf_to_json.png  page 1 of the W1 fee document next to the table step 1 extracted from it
dataset.png      how many question/answer pairs each step leaves, from the JSON in data/processed
"""
import io
import json
import textwrap

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pymupdf

from finchat.paths import PROCESSED, RAW, ROOT

OUT = ROOT / "docs" / "img"
OUT.mkdir(parents=True, exist_ok=True)

SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, RED = "#2a78d6", "#e34948"          # validated pair (dataviz palette slots 1 and 8)

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": GRID, "axes.labelcolor": INK_2, "xtick.color": INK_2, "ytick.color": INK_2,
    "text.color": INK, "font.size": 11, "axes.spines.top": False, "axes.spines.right": False,
})


def load(name):
    with open(PROCESSED / name, encoding="utf-8") as f:
        return json.load(f)


def short(cell, width=34):
    cell = " ".join(cell.split())
    return cell if len(cell) <= width else cell[: width - 1] + "…"


def pdf_to_json():
    page = pymupdf.open(RAW / "W1_Tarifas transferencias Extranjero.pdf")[0]
    clip = pymupdf.Rect(60, 185, 535, 662)                     # the "transferencias emitidas" table
    pix = page.get_pixmap(matrix=pymupdf.Matrix(3, 3), clip=clip)
    img = plt.imread(io.BytesIO(pix.tobytes("png")), format="png")

    table = load("_1_w1.json")["tables"][0]
    lines = ["{", f'  "title": "{table["title"]}",', '  "data": [']
    for row in table["data"][:4]:
        cells = [f'"{short(c)}"' for c in row]
        body = textwrap.wrap(", ".join(cells), 62, break_on_hyphens=False)
        lines.append("    [" + body[0])
        lines += ["     " + b for b in body[1:]]
        lines[-1] += "],"
    lines += [f"    … {len(table['data']) - 4} more rows", "  ]", "}"]

    fig = plt.figure(figsize=(14, 6.4), dpi=150)
    ax_pdf = fig.add_axes([0.01, 0.03, 0.40, 0.84])
    ax_pdf.imshow(img)
    ax_pdf.set_axis_off()
    ax_json = fig.add_axes([0.46, 0.03, 0.53, 0.84])
    ax_json.set_axis_off()
    ax_json.text(0, 1, "\n".join(lines), va="top", ha="left", family="DejaVu Sans Mono", fontsize=9.6,
                 color=INK, linespacing=1.45, transform=ax_json.transAxes)
    ax_json.text(0, 0.30, "The column names (Canales de emisión, Moneda, Límite, …) are not kept:\n"
                 "step 2 then takes the SEPA row as the header of every answer.",
                 va="bottom", ha="left", fontsize=10, color=RED, transform=ax_json.transAxes)

    fig.text(0.01, 0.95, "data/raw/W1_Tarifas transferencias Extranjero.pdf, page 1", fontsize=12, color=INK)
    fig.text(0.46, 0.95, "data/processed/_1_w1.json, first table", fontsize=12, color=INK)
    fig.text(0.01, 0.905, "Step 1 reads the .docx made from this PDF, with python-docx", fontsize=10, color=INK_2)
    fig.text(0.46, 0.905, f"{len(table['data'])} rows; columns that hold one value in every row are dropped",
             fontsize=10, color=INK_2)
    fig.patches.append(matplotlib.patches.FancyArrowPatch((0.415, 0.5), (0.448, 0.5), transform=fig.transFigure,
                       arrowstyle="-|>", mutation_scale=22, color=INK_2, linewidth=1.6))
    fig.savefig(OUT / "pdf_to_json.png")
    print("wrote", OUT / "pdf_to_json.png")


def dataset():
    sections, tables, full = load("_2_generated_prompts_SECTIONS.json"), load("_2_generated_prompts_TABLE.json"), load("_2_generated_prompts_FULL.json")
    kept, checked = load("_3_generated_prompts_FULL.json"), load("_3_generated_prompts_clean.json")
    origin = {(p["prompt"], p["response"]): "text" for p in sections}
    origin.update({(p["prompt"], p["response"]): "tables" for p in tables})

    def split(pairs):
        n = {"tables": 0, "text": 0, "hand-written": 0}
        for p in pairs:
            n[origin.get((p["prompt"], p["response"]), "hand-written")] += 1
        return ", ".join(f"{v:,} {k}" for k, v in n.items() if v)

    valid = [c for c in checked if c["valid"]]
    bars = [   # top to bottom
        ("Generated by step 2", "_2_generated_prompts_FULL.json", full, "step 4 trains on this file, unfiltered"),
        ("Kept by step 3's filter", "_3_generated_prompts_FULL.json", kept, None),
        ("Pass both step 3 checks", "_3_generated_prompts_clean.json", valid, None),
    ]
    fig, ax = plt.subplots(figsize=(12, 3.9), dpi=150)
    y = list(range(len(bars)))[::-1]
    ax.barh(y, [len(b[2]) for b in bars], height=0.56, color=BLUE)
    for yi, (label, file, pairs, note) in zip(y, bars):
        ax.text(-150, yi + 0.1, label, ha="right", va="center", fontsize=11.5, color=INK)
        ax.text(-150, yi - 0.17, file, ha="right", va="center", fontsize=9, color=INK_2, family="DejaVu Sans Mono")
        ax.text(len(pairs) + 90, yi + 0.1, f"{len(pairs):,} pairs", ha="left", va="center", fontsize=11.5, color=INK, weight="bold")
        ax.text(len(pairs) + 90, yi - 0.17, f"from {split(pairs)}", ha="left", va="center", fontsize=9.5, color=INK_2)
        if note:
            ax.text(len(pairs) + 90, yi + 0.42, note, ha="left", va="center", fontsize=10, color=RED)
    ax.set_xlim(0, 12500)
    ax.set_ylim(-0.6, len(bars) - 0.25)
    ax.set_yticks([])
    ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:,.0f}"))
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.spines["left"].set_visible(False)
    ax.set_title("Question/answer pairs in data/processed", loc="left", fontsize=13, x=-0.33, pad=14)
    fig.subplots_adjust(left=0.25, right=0.98, top=0.86, bottom=0.1)
    fig.savefig(OUT / "dataset.png")
    print("wrote", OUT / "dataset.png", [len(b[2]) for b in bars])


if __name__ == "__main__":
    pdf_to_json()
    dataset()
